local self = {}

-- True only while drawButton draws a button whose mon is shiny; read by the icon path override.
self.drawingShinyIcon = false

function self.setIconOption()
    for i = 1, #Options.IconSetMap do
        if Options.IconSetMap[i].name == "RogueMon" then
            --Utils.printDebug("[WARN] RogueMon icon set already loaded")
            return
        end
    end
    
    local numIconSets = #Options.IconSetMap
    local s = FileManager.slash
    local folder = string.format("..%s..%sextensions%sroguemon-expansion%sgraphics", s, s, s, s)
    Options.IconSetMap[numIconSets + 1] = {
        name = "RogueMon",
        author = "cawtds", -- ROGUEMON-TODO - correct attribution?
        folder = folder,
        -- Generated by rom/tools/shiny-icons/generate-shiny-icons.py
        shinyFolder = folder .. s .. "shiny",
        extension = ".png",
        yOffset = 0,
        adjustQuestionMark = true,
    }
    
    Options["Pokemon icon set"] = numIconSets + 1
end

-- The core resolves every icon through Drawing.ImagePaths.PokemonIcon, which is given only the
-- species id. Buttons that show one specific mon carry isShinyIcon; drawButton raises
-- drawingShinyIcon around the core draw for them, and this override then points the path into
-- the icon set's shiny folder. Icon sets without a shinyFolder draw as before.
function self.setShinyIconPath()
    local iconPath = Drawing.ImagePaths.PokemonIcon
    iconPath.shouldUseOverride = function(_, _)
        return self.drawingShinyIcon and Options.getIconSet().shinyFolder ~= nil
    end
    iconPath.getOverridePath = function(_, value)
        local iconset = Options.getIconSet()
        return FileManager.buildImagePath(iconset.shinyFolder, tostring(value), iconset.extension)
    end

    TrackerScreen.Buttons.PokemonIcon.isShinyIcon = function(_)
        return (Tracker.getViewedPokemon() or Tracker.getDefaultPokemon()).isShiny == true
    end
    GameOverScreen.Buttons.PokemonIcon.isShinyIcon = function(button)
        return (Tracker.getPokemon(button.teamIndex or 1, true) or Tracker.getDefaultPokemon()).isShiny == true
    end
end

return self
