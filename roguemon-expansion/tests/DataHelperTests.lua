-- Representative move IDs for sweep tests.
local TEST_MOVES = {
    1, 2, 10, 33, 50, 85, 100, 165, 200, 237, 250, 311, 355,
    400, 450, 500, 560, 600, 700, 800,
}

-- Type pair scenarios for sweep tests.
local TYPE_PAIRS = {
    { TYPE_NORMAL, TYPE_NORMAL, "Monotype Normal" },
    { TYPE_ICE,    TYPE_STEEL,  "Dual Ice/Steel" },
    { TYPE_FIRE,   TYPE_FAIRY,  "Dual Fire/Fairy" },
    { TYPE_NORMAL, TYPE_FIRE,   "Dual Normal/Fire" },
}

-- Test: Lua implementation (1-indexed arrays) matches golden values produced by
-- compiling and running the ROM's C CalcDistortedType (0-indexed, u32 arithmetic).
-- 240 data points across 3 type pairs × 8 seeds × 10 moves.
local function testGoldenValues()
    for i, gv in ipairs(GOLDEN_VALUES) do
        local seed, moveId, t1, t2, expected = gv[1], gv[2], gv[3], gv[4], gv[5]
        local result = calcDistortedType(seed, moveId, t1, t2)
        assert(result == expected, string.format(
            "Golden[%d]: seed=%d move=%d types=(%d,%d) expected=%d got=%s",
            i, seed, moveId, t1, t2, expected, tostring(result)))
    end
    return true
end

-- Test: distorted type never produces a disallowed type (NONE, MYSTERY, STELLAR).
-- Sweeps all 256 seeds × 20 moves × 4 type pairs = 20480 iterations.
local function testNoDisallowedTypes()
    for _, pair in ipairs(TYPE_PAIRS) do
        local t1, t2, label = pair[1], pair[2], pair[3]
        for seed = 0, 255 do
            for _, moveId in ipairs(TEST_MOVES) do
                local result = calcDistortedType(seed, moveId, t1, t2)
                assert(result ~= nil, string.format(
                    "%s seed=%d move=%d: got nil", label, seed, moveId))
                assert(not DISALLOWED[result], string.format(
                    "%s seed=%d move=%d: got disallowed type %d", label, seed, moveId, result))
            end
        end
    end
    return true
end

-- Test: distorted type never matches the Pokémon's own types (no STAB).
-- Sweeps all 256 seeds × 20 moves × 4 type pairs = 20480 iterations.
local function testNoStabTypes()
    for _, pair in ipairs(TYPE_PAIRS) do
        local t1, t2, label = pair[1], pair[2], pair[3]
        for seed = 0, 255 do
            for _, moveId in ipairs(TEST_MOVES) do
                local result = calcDistortedType(seed, moveId, t1, t2)
                assert(result ~= t1, string.format(
                    "%s seed=%d move=%d: got own type1 %d", label, seed, moveId, t1))
                assert(result ~= t2, string.format(
                    "%s seed=%d move=%d: got own type2 %d", label, seed, moveId, t2))
            end
        end
    end
    return true
end

-- Test: result is always a valid battle type index (1-19 excluding MYSTERY).
local function testResultInValidRange()
    local VALID = {}
    for i = 0, NUMBER_OF_MON_TYPES - 1 do
        if not DISALLOWED[i] then
            VALID[i] = true
        end
    end

    for seed = 0, 255 do
        for _, moveId in ipairs(TEST_MOVES) do
            local result = calcDistortedType(seed, moveId, TYPE_ICE, TYPE_STEEL)
            assert(VALID[result], string.format(
                "seed=%d move=%d: result %d not in valid type range", seed, moveId, result))
        end
    end
    return true
end

function DataHelperTests.run()
    Utils.printDebug("[TEST] Running DataHelper tests")
    local tests = Roguemon.Tests

    local results = {
        tests.runTest("golden values match ROM C output", testGoldenValues),
        tests.runTest("no disallowed types across 256 seeds", testNoDisallowedTypes),
        tests.runTest("no STAB types across 256 seeds", testNoStabTypes),
        tests.runTest("result in valid type range", testResultInValidRange),
    }

    local allPassed = true
    for _, ok in ipairs(results) do
        if not ok then allPassed = false; break end
    end

    if not allPassed then
        Utils.printDebug("[WARN] DataHelper tests completed with failures")
    else
        Utils.printDebug("[TEST] DataHelper tests passed")
    end
end

return DataHelperTests
