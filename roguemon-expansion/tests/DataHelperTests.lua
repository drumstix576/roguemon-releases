-- Mirror of ROM's type enum (constants/pokemon.h)
local TYPE_NONE    = 0
local TYPE_NORMAL  = 1
local TYPE_STEEL   = 9
local TYPE_MYSTERY = 10
local TYPE_FIRE    = 11
local TYPE_ICE     = 16
local TYPE_FAIRY   = 19
local TYPE_STELLAR = 20
local NUMBER_OF_MON_TYPES = 21

-- Disallowed types that must never appear as a distorted result.
local DISALLOWED = { [TYPE_NONE] = true, [TYPE_MYSTERY] = true, [TYPE_STELLAR] = true }

-- Same algorithm using 1-indexed arrays, matching the tracker's Lua idiom
-- (DataHelper.lua getDistortedMoveType). Compared against the golden values
-- below, which were generated by the ROM's C implementation using 0-indexed
-- arrays and u32 arithmetic.
local function calcDistortedType(seed, moveId, type1Idx, type2Idx)
    local validTypes = {}
    for i = 0, NUMBER_OF_MON_TYPES - 1 do
        if i ~= TYPE_NONE and i ~= TYPE_MYSTERY and i ~= TYPE_STELLAR
            and i ~= type1Idx and i ~= type2Idx then
            validTypes[#validTypes + 1] = i
        end
    end
    if #validTypes == 0 then return nil end

    local hash = seed
    hash = hash ~ (moveId << 3)
    hash = hash ~ (moveId >> 2)
    hash = (hash + moveId * 37) & 0xFFFFFFFF
    hash = hash ~ (hash >> 8)

    return validTypes[(hash % #validTypes) + 1]
end

